#!/usr/bin/env node
/**
 * Dependency licence audit. Walks node_modules for every PRODUCTION dependency (transitively), reads each
 * package's declared SPDX licence and checks it against a GPL-3.0-compatible allow-list.
 *   node scripts/licenses.mjs           → prints a table, exits 1 if anything is unknown or incompatible
 *   node scripts/licenses.mjs --write   → also writes docs/DEPENDENCY_LICENSES.md
 * It reads declared metadata only; it is a safeguard, not legal advice.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

// SPDX identifiers that may be combined into a GPL-3.0 work (permissive, or GPL-compatible copyleft).
const OK = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'Apache-2.0', 'BlueOak-1.0.0', 'CC0-1.0', 'Unlicense', 'Zlib', 'MPL-2.0', 'LGPL-3.0', 'LGPL-3.0-only', 'LGPL-3.0-or-later', 'LGPL-2.1', 'LGPL-2.1-or-later', 'GPL-3.0', 'GPL-3.0-only', 'GPL-3.0-or-later', 'Python-2.0', 'CC-BY-4.0', 'BSD'])
const BAD = /(^|[^L])GPL-2\.0-only|AGPL|SSPL|BUSL|Commons-Clause|CC-BY-NC|PolyForm-Noncommercial|UNLICENSED|SEE LICENSE/i

const seen = new Map()
function resolve(name, from) {
  let dir = from
  for (;;) {
    const p = join(dir, 'node_modules', name, 'package.json')
    if (existsSync(p)) return p
    const up = join(dir, '..')
    if (up === dir || dir === '/') return null
    dir = up
  }
}
function walk(name, from) {
  const p = resolve(name, from)
  if (!p || seen.has(p)) return
  const j = JSON.parse(readFileSync(p, 'utf8'))
  const lic = typeof j.license === 'string' ? j.license : j.license?.type ?? (Array.isArray(j.licenses) ? j.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN')
  seen.set(p, { name: j.name, version: j.version, license: lic, homepage: j.homepage ?? j.repository?.url ?? '' })
  const base = p.replace(/package\.json$/, '')
  for (const dep of Object.keys({ ...j.dependencies, ...j.optionalDependencies })) walk(dep, base)
}
for (const dep of Object.keys(pkg.dependencies ?? {})) walk(dep, root)

// For "A OR B" expressions one acceptable alternative is enough; "A AND B" needs both.
function acceptable(expr) {
  const e = expr.replace(/[()]/g, ' ').trim()
  if (BAD.test(e)) return false
  const ors = e.split(/\s+OR\s+/i)
  return ors.some((o) => o.split(/\s+AND\s+/i).every((t) => OK.has(t.trim())))
}

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name))
const bad = rows.filter((r) => !acceptable(r.license))
const counts = rows.reduce((m, r) => ((m[r.license] = (m[r.license] ?? 0) + 1), m), {})

console.log(`${rows.length} production packages (transitive)`)
for (const [l, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(3)}  ${l}`)
if (bad.length) { console.log('\nNeeds review:'); for (const r of bad) console.log(`  ${r.name}@${r.version}  ${r.license}`) }

if (process.argv.includes('--write')) {
  const md = [
    '# Dependency licences', '',
    `OpenSong is licensed under **GPL-3.0-only**. This file is generated by \`npm run licenses -- --write\` from the **production** dependency tree (${rows.length} packages, including transitive ones) and was produced from \`package-lock.json\` as installed. It lists each package's *declared* licence; it is an automated check, not legal advice.`, '',
    '## Summary', '', '| Licence | Packages |', '|---|---|', ...Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`), '',
    bad.length ? `## ⚠️ Needs review\n\n${bad.map((r) => `- ${r.name}@${r.version} — ${r.license}`).join('\n')}\n` : '**Result:** every production dependency declares a licence that can be combined with GPL-3.0 (permissive licences, MPL-2.0, or GPL-compatible copyleft).', '',
    '## Packages', '', '| Package | Version | Licence |', '|---|---|---|', ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`), '',
    '## Development-only tools', '', 'Vite, TypeScript, Tailwind CSS, Vitest, Playwright, ESLint-style tooling and vite-plugin-pwa are used to build and test OpenSong. They are not shipped to users, so their licences do not affect the distributed app (check them in `package.json` → `devDependencies`).', '',
  ].join('\n')
  writeFileSync(join(root, 'docs/DEPENDENCY_LICENSES.md'), md)
  console.log('\nWrote docs/DEPENDENCY_LICENSES.md')
}
process.exit(bad.length ? 1 : 0)
